const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
import fs from 'node:fs/promises';
import path from 'node:path';
const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:4173';
const root = path.resolve(import.meta.dirname, '..');
await fs.mkdir(path.join(root, 'artifacts'), {recursive:true});
const browser = await chromium.launch({headless:true, ...(process.env.CHROME_PATH ? {executablePath:process.env.CHROME_PATH} : {channel:'chrome'}), args:['--disable-background-networking']});
const context = await browser.newContext({viewport:{width:1440,height:1050},deviceScaleFactor:1,permissions:['clipboard-read','clipboard-write']});
const page = await context.newPage();
const errors = [], requests = [], checks = [];
page.on('pageerror', (error) => errors.push(String(error)));
context.on('request', (request) => requests.push(request.url()));
const check = (name, condition, detail='') => {checks.push({name,passed:!!condition,detail}); if(!condition) throw new Error(name+': '+detail);};
try {
  await page.goto(base, {waitUntil:'networkidle'});
  await page.waitForFunction(()=>document.documentElement.dataset.engine === 'ready', null, {timeout:90000});
  await page.waitForFunction(()=>document.querySelectorAll('.emoji-button').length>0);
  check('English Enoki interface', await page.title() === 'Enoki — Japanese at your fingertips' && await page.locator('html').getAttribute('lang') === 'en');
  const emojiLabels = await page.locator('.emoji-button, #emoji-categories button').evaluateAll(nodes => nodes.map(node => node.getAttribute('aria-label')));
  check('English emoji and category labels', emojiLabels.every(label => label && !/[ぁ-んァ-ヶ一-龠]/.test(label)));
  await page.locator('#licenses-button').click();
  await page.waitForFunction(()=>document.querySelectorAll('.license-entry').length===9);
  const catalog = JSON.parse(await fs.readFile(path.join(root,'licenses/catalog.json'),'utf8'));
  const displayedNotices = await page.locator('.license-entry pre').allTextContents();
  check('All nine full license texts are available', JSON.stringify(displayedNotices) === JSON.stringify(catalog.map(item=>item.text)));
  await page.locator('.license-entry summary').first().click();
  await page.screenshot({path:path.join(root,'artifacts/licenses-desktop.png'),fullPage:true});
  await page.keyboard.press('Escape');
  check('Escape closes licenses and restores focus', !(await page.locator('#licenses-dialog').isVisible()) && await page.locator('#licenses-button').evaluate(node=>node===document.activeElement));
  check('Empty initial editor', await page.locator('#editor').inputValue() === '');
  await page.locator('#editor').click();
  await page.keyboard.type('nihongo');
  check('Romaji to hiragana', await page.locator('#editor').inputValue() === 'にほんご');
  await page.keyboard.press('Space');
  await page.waitForFunction(()=>document.querySelector('#editor').value.includes('日本語'));
  check('Real Mozc kanji conversion', await page.locator('#editor').inputValue() === '日本語');
  check('Multiple conversion candidates', await page.locator('#candidates .candidate').count()>1);
  await page.keyboard.press('Enter');
  await page.keyboard.type('nyuuryoku');
  await page.keyboard.press('Space');
  await page.waitForFunction(()=>document.querySelector('#editor').value.includes('入力'));
  await page.keyboard.press('Enter');
  check('Consecutive compositions', await page.locator('#editor').inputValue() === '日本語入力');
  await page.locator('#copy-button').click();
  check('Clipboard contains committed text', await page.evaluate(()=>navigator.clipboard.readText()) === '日本語入力');
  await page.locator('#clear-button').click();
  check('Clear', await page.locator('#editor').inputValue()==='');
  await page.locator('#undo-button').click();
  check('Undo clear', await page.locator('#editor').inputValue()==='日本語入力');
  await page.keyboard.press('End');
  await page.keyboard.type('tesuto');
  await page.keyboard.press('Control+z');
  check('Cancel preedit with undo', await page.locator('#editor').inputValue()==='日本語入力');
  await page.locator('#clear-button').click();
  await page.keyboard.type('toukyoudeashitakaigigaarimasu');
  await page.keyboard.press('Space');
  await page.waitForFunction(()=>document.querySelectorAll('#composition .segment').length>1 && document.querySelector('#candidates .candidate'));
  const first = await page.locator('#editor').inputValue();
  await page.keyboard.press('ArrowRight');
  check('Move between segments', await page.locator('#composition .active').textContent() === '明日');
  await page.keyboard.press('Shift+ArrowRight');
  await page.waitForTimeout(200);
  check('Resize composition remains usable', await page.locator('#composition .segment').count()>0);
  await page.keyboard.press('Enter');
  check('Confirm multi-segment text', (await page.locator('#editor').inputValue()).length>0);
  await page.locator('#clear-button').click();
  await page.keyboard.type('otsukaresamadesu.');
  await page.keyboard.press('Space');
  await page.waitForFunction(()=>document.querySelector('#candidates .candidate'));
  await page.keyboard.press('Enter');
  await page.keyboard.press('Enter');
  await page.keyboard.type('toukyoudeashitakaigigaarimasu');
  await page.keyboard.press('Space');
  await page.waitForFunction(()=>document.querySelectorAll('#composition .segment').length>1 && document.querySelector('#candidates .candidate'));
  await page.keyboard.press('ArrowRight');
  await page.keyboard.press('ArrowRight');
  await page.waitForFunction(()=>document.querySelector('#toast').hidden);
  await page.screenshot({path:path.join(root,'artifacts/conversion-desktop.png'),fullPage:true});
  await page.keyboard.press('Enter');
  await page.locator('#emoji-search').click();
  await page.keyboard.type('neko');
  await page.keyboard.press('Space');
  await page.waitForFunction(()=>document.querySelector('#emoji-search').value.includes('猫'));
  await page.keyboard.press('Enter');
  check('Japanese IME in emoji search', (await page.locator('#emoji-search').inputValue()).includes('猫'));
  check('Emoji Japanese search results', await page.locator('.emoji-button').count()>0);
  const beforeEmoji = await page.locator('#editor').inputValue();
  const insertedEmoji = await page.locator('.emoji-button').first().textContent();
  await page.locator('.emoji-button').first().click();
  check('Insert emoji at editor caret', await page.locator('#editor').inputValue() === beforeEmoji + insertedEmoji);
  const actualCount = await page.locator('#char-count').textContent();
  const expectedCount = await page.evaluate(()=>[...new Intl.Segmenter('ja',{granularity:'grapheme'}).segment(document.querySelector('#editor').value)].length);
  check('Grapheme character count', Number(actualCount.replaceAll(',',''))===expectedCount);
  await page.screenshot({path:path.join(root,'artifacts/emoji-desktop.png'),fullPage:true});
  await page.waitForFunction(()=>document.documentElement.dataset.offline === 'ready', null, {timeout:90000});
  await context.setOffline(true);
  await page.reload({waitUntil:'networkidle'});
  await page.waitForFunction(()=>document.documentElement.dataset.engine==='ready');
  check('Text is not persisted after reload', await page.locator('#editor').inputValue()==='');
  await page.locator('#editor').click();
  await page.keyboard.type('nihongo');
  await page.keyboard.press('Space');
  await page.waitForFunction(()=>document.querySelector('#editor').value==='日本語');
  check('Offline kanji conversion', await page.locator('#editor').inputValue()==='日本語');
  await page.keyboard.press('Enter');
  await page.locator('#ime-toggle').click();
  await page.locator('#emoji-search').fill('cat');
  check('Offline English emoji search', await page.locator('.emoji-button').count()>0);
  await page.locator('#licenses-button').click();
  await page.waitForFunction(()=>document.querySelectorAll('.license-entry').length===9);
  check('Full licenses survive offline reload', JSON.stringify(await page.locator('.license-entry pre').allTextContents()) === JSON.stringify(displayedNotices));
  await page.locator('.license-entry summary').nth(5).click();
  check('Apache terms are readable offline', await page.locator('.license-entry').nth(5).innerText().then(text=>text.includes('END OF TERMS AND CONDITIONS')));
  await page.locator('#licenses-close').click();
  await context.setOffline(false);
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(root,'artifacts/mobile.png'),fullPage:true});
  check('No horizontal overflow on mobile', await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  check('No external requests', requests.every((value)=>value.startsWith(base)));
  check('No runtime JS errors', errors.length===0,errors.join('\n'));
  console.log(JSON.stringify({browser:browser.version(),checks,requests:[...new Set(requests)]},null,2));
} catch(error) {
  await page.screenshot({path:path.join(root,'artifacts/failure.png'),fullPage:true}).catch(()=>{});
  console.error(error);
  console.log(JSON.stringify({checks,errors,url:page.url(),body:await page.locator('body').innerText()},null,2));
  process.exitCode=1;
} finally {
  await fs.writeFile(path.join(root,'artifacts/test-results.json'),JSON.stringify({checks,errors,browser:browser.version()},null,2));
  await browser.close();
}
